"""Pytest bootstrap: put the repository root (the package parent) on sys.path.

Belt-and-braces alongside ``[tool.pytest.ini_options] pythonpath`` so the
suite also runs from any working directory via a bare ``pytest tests/``.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
